  // Helper to find any sign by id or label
  getSign: function(query) {
    if (!query) return null;
    const q = query.toString().trim().toLowerCase();
    const all = [...this.alphabets, ...this.numbers, ...this.words];
    return all.find(item => 
      item.id.toLowerCase() === q || 
      item.label.toLowerCase() === q || 
      item.title.toLowerCase() === q
    ) || null;
  },

  // Comprehensive multi-factor search across alphabets, words, sign names, categories, and hand types
  searchSigns: function(query, category) {
    const q = (query || "").trim().toLowerCase();
    let all = [...this.alphabets, ...this.numbers, ...this.words];

    // Filter by category pill if selected
    if (category && category !== "all") {
      const catLower = category.toLowerCase();
      if (catLower === "common words") {
        // Include common words and everyday dialogue signs
        all = all.filter(item => 
          item.category.toLowerCase() === "common words" || 
          item.category.toLowerCase() === "everyday communication"
        );
      } else {
        all = all.filter(item => item.category.toLowerCase() === catLower);
      }
    }

    if (!q) return all;

    const scored = [];
    all.forEach(item => {
      const label = (item.label || "").toLowerCase();
      const title = (item.title || "").toLowerCase();
      const id = (item.id || "").toLowerCase();
      const cat = (item.category || "").toLowerCase();
      const desc = (item.desc || "").toLowerCase();
      const variations = (item.variations || "").toLowerCase();
      
      let score = 0;

      // 1. Exact match on label or id (Highest priority, e.g. "A" -> Letter A, "5" -> Number 5)
      if (label === q || id === q) {
        score += 100;
      } else if (label.startsWith(q)) {
        score += 80;
      } else if (title.startsWith(q) || title.includes(" " + q)) {
        score += 70;
      } else if (title.includes(q)) {
        score += 50;
      }

      // 2. Category / Keyword query
      if ((q === "alphabet" || q === "alphabets" || q === "letter" || q === "letters") && cat === "alphabets") {
        score += 60;
      }
      if ((q === "number" || q === "numbers" || q === "numeral" || q === "digit") && cat === "numbers") {
        score += 60;
      }
      if ((q === "greeting" || q === "greetings") && cat === "greetings") {
        score += 60;
      }
      if ((q === "word" || q === "words" || q === "common") && (cat === "common words" || cat === "everyday communication")) {
        score += 60;
      }

      // 3. Hand type query
      if ((q === "two-handed" || q === "two hands" || q === "2 hands") && item.twoHanded) {
        score += 40;
      }
      if ((q === "one-handed" || q === "one hand" || q === "1 hand") && !item.twoHanded) {
        score += 40;
      }

      // 4. Variations match
      if (variations.includes(q)) {
        score += 30;
      }

      // 5. Description match (only for query length > 1 to avoid single letter matching every sentence)
      if (q.length > 1 && desc.includes(q)) {
        score += 20;
      }

      if (score > 0) {
        scored.push({ item, score });
      }
    });

    // Sort by highest relevance score
    scored.sort((a, b) => b.score - a.score);
    return scored.map(s => s.item);
  }
